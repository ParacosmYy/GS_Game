/**
 * Ryo Sakazaki crouch animation — high-resolution pixel frames
 *
 * CROUCH:   4-frame crouch idle loop (breathing while low), 48×72 px
 * CROUCH_A: 3-frame crouch light punch (low jab), 48×72 px
 * CROUCH_C: 4-frame crouch heavy punch (low uppercut), 48×72 px
 * Same 14-color palette as ryoIdleFrames.ts / ryoAttackFrames.ts.
 *
 * Palette
 * -------
 *  0  transparent
 *  1  #0c0a08  outline / deepest shadow
 *  2  #1a1208  hair dark
 *  3  #3a2818  hair mid
 *  4  #5a3a22  hair light
 *  5  #f0c090  skin light
 *  6  #d09060  skin mid
 *  7  #a06838  skin dark
 *  8  #f8f4ec  gi light (white)
 *  9  #e0d8c8  gi mid
 * 10  #c0b8a8  gi dark (shadow)
 * 11  #181410  belt / eyes
 * 12  #ffffff  eye white / highlight
 * 13  #c83030  headband
 */

export interface PixelFrame {
  width: number;
  height: number;
  palette: Record<number, string>;
  pixels: number[][]; // height rows × width cols, 0 = transparent
  anchor: { x: number; y: number };
}

