// ─────────────────────────────────────────────────────────────
// Encoding: each char maps to a palette index
// '.' = 0 (transparent)
// '0'-'9' = indices 0-9
// 'a'-'n' = indices 10-23
// ─────────────────────────────────────────────────────────────

const CHARS = '.0123456789abcdefghijklmn'.split('');
const W = 96;
function r(s: string): number[] {
  const padded = s.padEnd(W, '.').slice(0, W);
  return padded.split('').map(ch => {
    const idx = CHARS.indexOf(ch);
    return idx >= 0 ? idx : 0;
  });
}

