/**
 * Ryo Sakazaki jump animation — SNK KOF2002 style pixel frames
 *
 * 6-frame jump arc, 96x144 px each, 24-color palette.
 * Style target: SNK KOF2002 — clean outlines, multi-level inner shadows, warm palette.
 *
 * Jump sequence: crouch_prep -> launch -> rising -> peak -> falling -> landing
 * Anchor { x: 48, y: 144 } = ground reference point.
 * Airborne frames have transparent space below the character.
 *
 * Encoding: '.' = transparent (0), '1'-'9' = palette 1-9, 'a'-'n' = palette 10-23
 */

export interface PixelFrame {
  width: number;
  height: number;
  palette: Record<number, string>;
  pixels: number[][]; // height rows x width cols, 0 = transparent
  anchor: { x: number; y: number };
}

