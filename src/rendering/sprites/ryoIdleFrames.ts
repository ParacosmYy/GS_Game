// ─────────────────────────────────────────────────────────────
// Helper — row shorthand builders
// Each row is 48 cells wide.  We use compact string slices for
// readability: characters '0'-'9','a','b','c','d' map to palette
// indices 0-13.
// ─────────────────────────────────────────────────────────────

const C = '.0123456789abcd'.split('');
const W = 48; // frame width
function r(s: string): number[] {
  // Pad or trim to exactly W columns
  const padded = s.padEnd(W, '.').slice(0, W);
  return padded.split('').map(ch => {
    const idx = C.indexOf(ch);
    return idx >= 0 ? idx : 0;
  });
}

