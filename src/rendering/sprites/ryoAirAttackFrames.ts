// ─────────────────────────────────────────────────────────────
// Helper — row shorthand builders (same as idle/jump)
// Characters '0'-'9','a','b','c','d' map to palette indices 0-13.
// '.' is a shorthand for transparent (0).
// ─────────────────────────────────────────────────────────────

const C = '.0123456789abcd'.split('');
const W = 48; // frame width
function r(s: string): number[] {
  const padded = s.padEnd(W, '.').slice(0, W);
  return padded.split('').map(ch => {
    const idx = C.indexOf(ch);
    return idx >= 0 ? idx : 0;
  });
}

