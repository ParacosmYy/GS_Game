/**
 * ryoAirAttackFrames.ts
 *
 * Ryo Sakazaki air attack frames: AIR_A (3f), AIR_C (4f), AIR_D (4f).
 * 48x72 px, same palette as ryoIdleFrames.ts.
 * Reuses jump frame J2 (rising) for startup/recovery to maintain
 * visual continuity between JUMP and AIR_ATTACK states.
 */

export interface PixelFrame {
  width: number;
  height: number;
  palette: Record<number, string>;
  pixels: number[][];
  anchor: { x: number; y: number };
}

const PALETTE: Record<number, string> = {
  0: 'transparent', 1: '#0c0a08', 2: '#1a1208', 3: '#3a2818',
  4: '#5a3a22', 5: '#f0c090', 6: '#d09060', 7: '#a06838',
  8: '#f8f4ec', 9: '#e0d8c8', 10: '#c0b8a8', 11: '#181410',
  12: '#ffffff', 13: '#c83030',
};

const C = '.0123456789abcd'.split('');
const W = 48;
function r(s: string): number[] {
  const padded = s.padEnd(W, '.').slice(0, W);
  return padded.split('').map(ch => { const idx = C.indexOf(ch); return idx >= 0 ? idx : 0; });
}

